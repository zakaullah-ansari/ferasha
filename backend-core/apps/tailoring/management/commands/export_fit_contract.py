"""Export the bespoke fit contract as JSON for the frontend to consume.

The frontend must validate measurements with *exactly* the ranges the backend
enforces. Hand-copying them guarantees eventual drift, and drift here has two
bad outcomes:

* frontend stricter than backend — a real customer's real measurement is
  rejected with no way to proceed;
* frontend looser than backend — the customer fills a long form and is then
  refused by the API, or worse, the value is accepted and a tailor cuts cloth
  from a typo.

So the Python definitions are the single source of truth and this command is
the only way they reach TypeScript.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from django.core.management.base import BaseCommand

from apps.tailoring.validators import (
    MEASUREMENT_RANGES,
    REQUIRED_BY_GARMENT,
)


def build_contract() -> dict[str, Any]:
    """Serialise the fit contract to plain JSON-able data."""
    return {
        "$comment": (
            "GENERATED by `manage.py export_fit_contract`. Do not edit by hand. "
            "Source of truth: backend-core/apps/tailoring/validators.py"
        ),
        "unit": "inch",
        "measurements": {
            name: {
                "min": float(spec.min_in),
                "max": float(spec.max_in),
                "label": spec.label,
            }
            for name, spec in sorted(MEASUREMENT_RANGES.items())
        },
        "requiredByGarment": {
            garment: list(fields)
            for garment, fields in sorted(REQUIRED_BY_GARMENT.items())
        },
    }


class Command(BaseCommand):
    help = "Export the bespoke fit contract (ranges + required fields) as JSON."

    def add_arguments(self, parser):
        parser.add_argument(
            "--output",
            type=Path,
            default=None,
            help="File to write. Defaults to stdout.",
        )
        parser.add_argument(
            "--check",
            action="store_true",
            help="Exit non-zero if --output is missing or stale, without writing.",
        )

    def handle(self, *args, **options):
        payload = json.dumps(build_contract(), indent=2, sort_keys=True) + "\n"
        output: Path | None = options["output"]

        if output is None:
            self.stdout.write(payload)
            return

        if options["check"]:
            if not output.exists():
                self.stderr.write(f"{output} does not exist; run without --check.")
                raise SystemExit(1)
            if output.read_text(encoding="utf-8") != payload:
                self.stderr.write(
                    f"{output} is stale. Regenerate it: "
                    f"manage.py export_fit_contract --output {output}"
                )
                raise SystemExit(1)
            self.stdout.write(self.style.SUCCESS(f"{output} is up to date."))
            return

        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(payload, encoding="utf-8")
        self.stdout.write(
            self.style.SUCCESS(
                f"Wrote {len(build_contract()['measurements'])} measurement ranges "
                f"to {output}."
            )
        )
